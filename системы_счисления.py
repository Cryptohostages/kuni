"""Перевод чисел из одной системы счисления в другую (основания 2..36).

Что умеет:
  * целые и дробные числа (разделитель — точка или запятая);
  * отрицательные числа;
  * любые основания от 2 до 36 (цифры 0-9, затем буквы A-Z);
  * перевод сразу во все системы счисления.

Запуск:
    python системы_счисления.py 1010 2 16     ->  A
    python системы_счисления.py 255 10 2      ->  11111111
    python системы_счисления.py 3.625 10      ->  таблица по всем основаниям
    python системы_счисления.py               ->  интерактивный режим
"""

import sys
from fractions import Fraction

# Цифры для оснований до 36: 0-9, затем A-Z.
ЦИФРЫ = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ"

МИН_ОСНОВАНИЕ = 2
МАКС_ОСНОВАНИЕ = len(ЦИФРЫ)   # 36

# Сколько знаков после точки оставлять у дробной части.
ЗНАКОВ_ПО_УМОЛЧАНИЮ = 12


def проверить_основание(основание):
    """Основание должно быть целым числом от 2 до 36."""
    if not isinstance(основание, int) or isinstance(основание, bool):
        raise TypeError(f"Основание должно быть целым числом, а не {основание!r}")
    if not МИН_ОСНОВАНИЕ <= основание <= МАКС_ОСНОВАНИЕ:
        raise ValueError(
            f"Основание {основание} вне диапазона "
            f"{МИН_ОСНОВАНИЕ}..{МАКС_ОСНОВАНИЕ}"
        )
    return основание


def значение_цифры(цифра, основание):
    """'A' -> 10. Ругается, если цифра не подходит основанию."""
    место = ЦИФРЫ.find(цифра)
    if место == -1 or место >= основание:
        raise ValueError(
            f"Цифра {цифра!r} недопустима в системе с основанием {основание}"
        )
    return место


def в_десятичную(число, основание):
    """Строка в системе `основание` -> точное значение (Fraction).

    Дробь считается через Fraction, поэтому 0.1 в троичной системе
    не «уплывает», как это было бы с float.
    """
    проверить_основание(основание)

    текст = str(число).strip().upper().replace(" ", "").replace("_", "")
    текст = текст.replace(",", ".")

    знак = 1
    if текст[:1] in ("+", "-"):   # именно кортеж: "" in "+-" дало бы True
        знак = -1 if текст[0] == "-" else 1
        текст = текст[1:]

    целая, точка, дробная = текст.partition(".")
    if not целая and not дробная:
        raise ValueError("Пустое число")
    if точка and "." in дробная:
        raise ValueError(f"Слишком много точек в числе {число!r}")

    значение = Fraction(0)
    for цифра in целая:
        значение = значение * основание + значение_цифры(цифра, основание)

    множитель = Fraction(1, основание)
    for цифра in дробная:
        значение += значение_цифры(цифра, основание) * множитель
        множитель /= основание

    return знак * значение


def из_десятичной(значение, основание, знаков=ЗНАКОВ_ПО_УМОЛЧАНИЮ):
    """Число (int / float / Fraction / строка) -> запись в системе `основание`."""
    проверить_основание(основание)
    if знаков < 0:
        raise ValueError("Количество знаков не может быть отрицательным")

    # Сразу округляем до нужного числа знаков в целевой системе,
    # тогда разложение ниже конечное и цикл гарантированно закончится.
    масштаб = основание ** знаков
    значение = Fraction(round(Fraction(значение) * масштаб), масштаб)

    знак = "-" if значение < 0 else ""
    целая, дробная = divmod(abs(значение), 1)

    цифры = []
    while целая:
        целая, остаток = divmod(целая, основание)
        цифры.append(ЦИФРЫ[остаток])
    результат = знак + ("".join(reversed(цифры)) or "0")

    if дробная:
        хвост = []
        while дробная:
            дробная *= основание
            цифра, дробная = divmod(дробная, 1)
            хвост.append(ЦИФРЫ[цифра])
        результат += "." + "".join(хвост)

    return результат


def перевести(число, из_основания, в_основание, знаков=ЗНАКОВ_ПО_УМОЛЧАНИЮ):
    """Главная функция: перевод числа из одной системы в другую.

    >>> перевести("1010", 2, 16)
    'A'
    >>> перевести("255", 10, 2)
    '11111111'
    >>> перевести("-FF.8", 16, 10)
    '-255.5'
    """
    return из_десятичной(в_десятичную(число, из_основания), в_основание, знаков)


def во_все_системы(число, из_основания, знаков=ЗНАКОВ_ПО_УМОЛЧАНИЮ):
    """Перевод сразу во все системы счисления: {основание: запись}."""
    значение = в_десятичную(число, из_основания)
    return {
        основание: из_десятичной(значение, основание, знаков)
        for основание in range(МИН_ОСНОВАНИЕ, МАКС_ОСНОВАНИЕ + 1)
    }


def таблица(число, из_основания, знаков=ЗНАКОВ_ПО_УМОЛЧАНИЮ):
    """Красиво оформленная таблица со всеми системами счисления."""
    строки = [f"{число} (основание {из_основания}) во всех системах:"]
    названия = {2: "двоичная", 8: "восьмеричная", 10: "десятичная", 16: "шестнадцатеричная"}
    for основание, запись in во_все_системы(число, из_основания, знаков).items():
        подпись = названия.get(основание, "")
        строки.append(f"  {основание:>2}: {запись}" + (f"   ({подпись})" if подпись else ""))
    return "\n".join(строки)


def _спросить_основание(вопрос):
    while True:
        ответ = input(вопрос).strip()
        try:
            return проверить_основание(int(ответ))
        except (ValueError, TypeError) as ошибка:
            print(f"  Не годится: {ошибка}")


def интерактивно():
    """Диалог в консоли: спрашиваем число и основания, пока не скажут «выход»."""
    print("Перевод из одной системы счисления в другую (основания 2-36).")
    print("Пустая строка или «выход» — закончить.\n")
    while True:
        try:
            число = input("Число: ").strip()
        except EOFError:
            print()
            return
        if not число or число.lower() in {"выход", "exit", "quit", "q"}:
            return

        из_основания = _спросить_основание("Из какой системы (2-36): ")
        в_основание = input("В какую систему (2-36, Enter — во все): ").strip()

        try:
            if в_основание:
                итог = перевести(число, из_основания, проверить_основание(int(в_основание)))
                print(f"  = {итог}\n")
            else:
                print(таблица(число, из_основания) + "\n")
        except (ValueError, TypeError) as ошибка:
            print(f"  Ошибка: {ошибка}\n")


def main(аргументы=None):
    аргументы = list(sys.argv[1:] if аргументы is None else аргументы)

    if not аргументы:
        интерактивно()
        return 0

    if len(аргументы) not in (2, 3):
        print(__doc__)
        return 2

    число = аргументы[0]
    try:
        из_основания = проверить_основание(int(аргументы[1]))
        if len(аргументы) == 2:
            print(таблица(число, из_основания))
        else:
            в_основание = проверить_основание(int(аргументы[2]))
            print(перевести(число, из_основания, в_основание))
    except (ValueError, TypeError) as ошибка:
        print(f"Ошибка: {ошибка}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
